import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import ts from 'typescript';

const require = createRequire(import.meta.url);
const source = readFileSync(new URL('../app/api/intake/route.ts', import.meta.url), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const module = { exports: {} };
new Function('require', 'module', 'exports', output)(require, module, module.exports);
const { POST } = module.exports;
Object.assign(process.env, { RESEND_API_KEY: 'test-only', INTAKE_NOTIFY_EMAIL: 'info@stateofashes.com', INTAKE_FROM_EMAIL: 'State of Ashes <info@stateofashes.com>', INTAKE_AUTOREPLY_TEMPLATE_ID: 'diagnostic-received', SUPABASE_URL: 'https://storage.invalid', SUPABASE_SERVICE_ROLE_KEY: 'test-only' });
const messages = [];
let storageStatus = 201, notificationStatus = 200, replyStatus = 200;
globalThis.fetch = async (url, options) => {
  if (String(url).includes('/rest/v1/')) return new Response('{}', { status: storageStatus });
  const message = JSON.parse(options.body); messages.push(message);
  return new Response('{}', { status: message.template ? replyStatus : notificationStatus });
};
const submit = (overrides = {}) => POST(new Request('https://stateofashes.com/api/intake', { method: 'POST', headers: { host: 'stateofashes.com', origin: 'https://stateofashes.com' }, body: JSON.stringify({ name: 'Test Studio', email: 'visitor@example.com', bottleneck: 'Disconnected tools are slowing our work.', ...overrides }) }));
assert.equal((await submit()).status, 200);
assert.equal(messages.length, 2, 'accepted intake sends notification and acknowledgement');
assert.deepEqual(messages[0].to, ['info@stateofashes.com']);
assert.equal(messages[0].reply_to, 'visitor@example.com');
assert.deepEqual(messages[1].to, ['visitor@example.com']);
assert.equal(messages[1].reply_to, 'info@stateofashes.com');
assert.equal(messages[1].from, 'State of Ashes <info@stateofashes.com>');
assert.deepEqual(messages[1].template, { id: 'diagnostic-received' });
assert.equal(messages[1].html, undefined);
assert.equal(messages[1].subject, undefined, 'use the published template subject');
console.log('PASS: correct recipients, reply routing and published-template payload');
messages.length = 0; storageStatus = 500; notificationStatus = 500;
assert.equal((await submit()).status, 502);
assert.equal(messages.length, 1, 'never acknowledge an unreceived submission');
console.log('PASS: total delivery failure sends no acknowledgement');
messages.length = 0; storageStatus = 201; notificationStatus = 200; replyStatus = 500;
assert.equal((await submit()).status, 200);
assert.equal(messages.length, 2);
console.log('PASS: acknowledgement failure does not reject a received lead');
messages.length = 0; delete process.env.INTAKE_AUTOREPLY_TEMPLATE_ID;
assert.equal((await submit()).status, 200); assert.equal(messages.length, 1);
console.log('PASS: no template configured preserves notification-only behavior');
messages.length = 0;
assert.equal((await submit({ email: 'invalid' })).status, 400); assert.equal(messages.length, 0);
console.log('PASS: invalid submissions send no emails');
